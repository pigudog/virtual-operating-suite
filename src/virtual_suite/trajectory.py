"""Persistent virtual trajectories, separate from candidate forecast samples."""
from __future__ import annotations

from copy import copy, deepcopy

import numpy as np
import pandas as pd

from orgpt.features import EVT
from .world import Day, LATE, World


class EpisodeWorld(World):
    """One continuous virtual day initialised from observations at a fixed cutoff.

    Only the observed prefix is copied. Future events are generated by OR-GPT,
    kept between decision points and revealed as the virtual clock advances.
    An accepted schedule change regenerates future events conditional on the
    current virtual observations. Completed events remain fixed.
    """

    is_episode = True

    def __init__(self, source, day, cutoff, *, seed=0):
        if getattr(source, "is_episode", False):
            raise ValueError("Start independent episodes from the original World")
        if not np.isfinite(cutoff):
            raise ValueError("cutoff must be finite")
        self.__dict__.update(source.__dict__)
        self.now = float(cutoff)
        self._initial_cutoff = float(cutoff)
        self._rng = np.random.default_rng(seed)
        self._assignment = {r: list(gs) for r, gs in day.rooms.items()}
        self.day = Day(day.date, deepcopy(self._assignment), self)
        self._ids = {g for gs in self._assignment.values() for g in gs}
        if sum(map(len, self._assignment.values())) != len(self._ids):
            raise ValueError("A case cannot appear in more than one room")
        self.arrival = dict(source.arrival)
        self.forced_emergency = set(source.forced_emergency)
        self._pair_cache = {}
        self._path = {}
        self.history = []
        self._finished = False
        # Copy observations only; retain no factual future event queue.
        self.clk = {ev: np.full_like(values, np.inf, dtype=float)
                    for ev, values in source.clk.items()}
        self.c = source.c.copy(deep=True)
        self.enc = copy(source.enc)
        self.enc.c = self.c
        self.enc.key2rec = {}  # trajectory features must be recomputed
        for room, gs in self._assignment.items():
            for g in gs:
                if g in self.arrival:
                    continue  # injected cases have no factual timing in this day
                times = np.array([source.clk[ev][g] for ev in EVT], dtype=float)
                self._path[g] = np.where(times <= self.now, times, np.inf)
        self._publish()
        for r, gs in self._assignment.items():
            self._assignment[r] = ([g for g in gs if self.entry(g) <= self.now]
                                   + [g for g in gs if self.entry(g) > self.now])
        self.day.rooms = deepcopy(self._assignment)
        self._resample()

    def entry(self, g):
        # Injected cases become started once their virtual ENTRY has occurred.
        return float(self.clk["ENTRY"][g])

    def _publish(self):
        columns = ("or_entry", "surgery_start", "surgery_end", "or_exit")
        for g in self._ids:
            times = self._path.get(g, np.full(4, np.inf))
            for ev, col, value in zip(EVT, columns, times):
                observed = np.isfinite(value) and value <= self.now and self.known(g, self.now)
                self.clk[ev][g] = value if observed else np.inf
                if col in self.c:
                    self.c.loc[g, col] = (pd.Timestamp(self.day.date) + pd.Timedelta(minutes=float(value))) if observed else pd.NaT
        # Clock-bearing encoder fields are never used as a factual feature cache.
        self.enc.clk = self.clk

    def _validate_path(self):
        for room, gs in self._assignment.items():
            last_exit = -np.inf
            for g in gs:
                if g not in self._path:
                    continue
                values = self._path[g]
                if not np.isfinite(values).all() or np.any(np.diff(values) < 0):
                    raise ValueError(f"Invalid event sequence for case {g}")
                if values[0] < last_exit:
                    raise ValueError(f"Overlapping room occupancy in room {room}")
                if g in self.arrival and values[0] < self.arrival[g]:
                    raise ValueError("A case cannot enter before arrival")
                last_exit = values[3]

        self._validate_surgeon_path(
            {r: {g: self._path[g] for g in gs if g in self._path}
             for r, gs in self._assignment.items()}, self._initial_cutoff)

    def simulate(self, day, assignment, cutoff, n=20, rng=None, late=LATE, detail=False):
        if not np.isclose(cutoff, self.now, rtol=0, atol=1e-8):
            raise ValueError("Forecast at the current episode clock; use advance() to move forward")
        if day.date != self.day.date:
            raise ValueError("An episode can forecast only its own day")
        return super().simulate(day, assignment, cutoff, n=n, rng=rng, late=late, detail=detail)

    def _resample(self):
        """Generate futures for the suite from its current observed state."""
        visible = {r: [g for g in gs if self.known(g, self.now)]
                   for r, gs in self._assignment.items()}
        order, trajectories = self._suite_trajectories(self.day, visible, self.now, 1, self._rng)
        new_path = dict(self._path)
        for r, gs in order.items():
            for k, g in enumerate(gs):
                values = trajectories[r][0, k].astype(float)
                observed = np.array([self.clk[ev][g] for ev in EVT])
                mask = np.isfinite(observed)
                values[mask] = observed[mask]
                new_path[g] = values
        self._path = new_path
        self._validate_path()
        self._publish()

    def advance(self, t, state=None):
        """Reveal events through t; synchronise a policy's state when supplied.

        An arrival queued ahead of a case that has since entered joins the remaining
        queue instead: it cannot be inserted before already observed work.
        """
        if state is not None and state["assign"] != self._assignment:
            raise ValueError("Policy state does not match the committed episode")
        if not np.isfinite(t) or t < self.now:
            raise ValueError("The virtual clock must be finite and cannot go backwards")
        arrivals = sorted({a for g, a in self.arrival.items()
                           if g in self._ids and self.now < a <= t})
        for at in arrivals:
            self.now = float(at)
            self._publish()
            rooms = {r for r, gs in self._assignment.items()
                     if any(self.arrival.get(g) == at for g in gs)}
            for r in rooms:
                gs = self._assignment[r]
                self._assignment[r] = ([g for g in gs if self.entry(g) <= at]
                                       + [g for g in gs if self.entry(g) > at])
            self._resample()
        self.now = float(t)
        self._publish()
        if state is not None:
            state["assign"] = deepcopy(self._assignment)

    def commit(self, before, after, t):
        """Commit a gate-approved assignment and regenerate the virtual future.

        The safety gate and acceptance rule are applied by the coordinator. This
        boundary additionally enforces immutable observed history and case coverage.
        """
        if self._finished or t != self.now or before["assign"] != self._assignment:
            raise ValueError("Commit must use the current unfinished episode state")
        assignment = {r: list(gs) for r, gs in after["assign"].items()}
        if set(assignment) != set(self._assignment):
            raise ValueError("Cannot add or remove rooms during an episode")
        ids = [g for gs in assignment.values() for g in gs]
        if len(ids) != len(set(ids)) or set(ids) != self._ids:
            raise ValueError("Every case must occur exactly once in the schedule")
        for r, gs in self._assignment.items():
            observed = [g for g in gs if self.entry(g) <= self.now]
            if assignment[r][:len(observed)] != observed:
                raise ValueError("Cannot move or reorder an observed case")
        changed = {r for r in assignment if assignment[r] != self._assignment[r]}
        if not changed:
            return
        # Keep all completed observations, discard only future counterfactual endpoints.
        old_assignment, old_path = self._assignment, self._path
        rng_state = deepcopy(self._rng.bit_generator.state)
        self._assignment = assignment
        try:
            self._resample()
        except Exception:
            self._assignment, self._path = old_assignment, old_path
            self._rng.bit_generator.state = rng_state
            self._publish()
            raise
        self.history.append({"t": float(t), "assignment": deepcopy(assignment)})

    def finish(self, state=None, late=LATE):
        """Finish this realised day, including arrivals; never rewind its final plan."""
        pending = [a for g, a in self.arrival.items() if g in self._ids and a > self.now]
        if pending:
            self.advance(max(pending), state)
        finish = {r: max((self._path[g][3] for g in gs), default=self.now)
                  for r, gs in self._assignment.items() if gs}
        if finish:
            self.advance(max(self.now, max(finish.values())), state)
        self._finished = True
        return {"finish": {r: float(v) for r, v in finish.items()},
                "overtime_min": float(sum(max(v - late, 0.) for v in finish.values())),
                "late_rooms": int(sum(v > late for v in finish.values())),
                "events": {r: {g: self._path[g].tolist() for g in gs}
                           for r, gs in self._assignment.items()}}


def episode_world(world, day, cutoff=660.0):
    """Use an existing episode or initialise a continuous virtual day."""
    return world if getattr(world, "is_episode", False) else world.start_episode(day, cutoff)


def evaluate_policies(world, day, policies, *, repetitions, seed=0):
    """Rerun each policy in each independent virtual day (not fixed-plan rescoring).

    Policy signature: policy(episode_world, episode_day, decision_rng) -> (state, log).
    Environment seeds are matched across arms and separate from decision sampling.
    This is not a guarantee of identical case-level shocks after schedules diverge.
    """
    if repetitions < 1:
        raise ValueError("repetitions must be positive")
    rows = []
    for replicate, stream in enumerate(np.random.SeedSequence(seed).spawn(repetitions)):
        environment, decisions = stream.spawn(2)
        for name, policy in policies.items():
            episode = world.start_episode(day, seed=environment)
            state, _ = policy(episode, episode.day, np.random.default_rng(decisions))
            if state["assign"] != episode._assignment:
                raise ValueError("Policy changed its schedule without committing it to the episode")
            outcome = episode.finish(state)
            rows.append({"replicate": replicate, "policy": name,
                         "overtime_min": outcome["overtime_min"]})
    return rows
